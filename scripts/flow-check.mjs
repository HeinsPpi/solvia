import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'

const baseUrl = process.argv[2] || 'http://127.0.0.1:4173'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
page.setDefaultTimeout(10000)
const errors = []
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
page.on('pageerror', error => errors.push(error.message))
await mkdir('artifacts', { recursive: true })

await page.goto(baseUrl, { waitUntil: 'networkidle' })
await page.getByRole('heading', { name: '統合監視', exact: true }).waitFor()
await page.getByText('FusionSolar', { exact: true }).first().waitFor()
await page.screenshot({ path: 'artifacts/00-monitoring.png', fullPage: true })
await page.getByTestId('monitoring-incident-row').click()
await page.getByTestId('incident-page').waitFor()
await page.getByTestId('restart-ops').click()
await page.getByText('現地対応：必要', { exact: true }).waitFor()
await page.getByTestId('work-complete-ops').click()
await page.getByText('冷却ファン交換・PCS正常稼働', { exact: true }).waitFor()
await page.getByTestId('close-ops').click()
await page.getByText('案件完了', { exact: true }).waitFor()
await page.screenshot({ path: 'artifacts/00-incident-complete.png', fullPage: true })
await page.getByTestId('nav-inspection').click()
await page.getByRole('heading', { name: '点検予定', exact: true }).waitFor()
await page.getByText('今回の重点点検').waitFor()
await page.screenshot({ path: 'artifacts/01-inspection-list.png', fullPage: true })

await page.getByTestId('open-inspection').click()
await page.getByTestId('inspection-detail').waitFor()
await page.getByText('デモ用モックデータ').waitFor()

await page.getByTestId('history-tab').click()
await page.getByText('DCコネクタ接触不良', { exact: true }).waitFor()
await page.getByText('同一発電所・同一設備', { exact: true }).waitFor()

await page.getByTestId('priority-tab').click()
await page.getByTestId('priority-card').waitFor()
await page.getByText('なぜ見るのか').waitFor()
await page.screenshot({ path: 'artifacts/02-priority-inspection.png', fullPage: true })

await page.getByTestId('request-field').click()
await page.getByTestId('assignment-modal').waitFor()
const fieldUrl = await page.getByRole('link', { name: '現場画面を開く' }).getAttribute('href')
if (!fieldUrl) throw new Error('Field URL was not generated')
await page.screenshot({ path: 'artifacts/03-field-request.png', fullPage: true })

const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
mobile.setDefaultTimeout(15000)
mobile.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
mobile.on('pageerror', error => errors.push(error.message))
await mobile.goto(fieldUrl, { waitUntil: 'networkidle' })
await mobile.getByTestId('mobile-start').waitFor()
await mobile.screenshot({ path: 'artifacts/04-mobile-request.png', fullPage: true })
await mobile.getByTestId('start-inspection').click()

const photo = { name: 'inspection.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64') }
const chooseResult = async name => mobile.getByRole('button', { name: new RegExp(name) }).click()
const uploadVisiblePhotos = async () => {
  const inputs = mobile.locator('input[type="file"]')
  const count = await inputs.count()
  for (let index = 0; index < count; index += 1) {
    await inputs.nth(index).setInputFiles(photo)
    await mobile.getByText('同期中', { exact: true }).waitFor({ state: 'hidden' })
  }
}

await chooseResult('正常')
await uploadVisiblePhotos()
await mobile.getByRole('button', { name: '次の項目へ' }).click()
await chooseResult('異常')
await mobile.locator('textarea').fill('DCコネクタに変色あり')
await uploadVisiblePhotos()
await mobile.getByRole('button', { name: '次の項目へ' }).click()
await chooseResult('正常')
await mobile.getByTestId('measurement-input').fill('612')
await mobile.getByRole('button', { name: '次の項目へ' }).click()
await chooseResult('異常')
await mobile.locator('textarea').fill('北側パネル列に植生接近あり')
await uploadVisiblePhotos()
await mobile.getByTestId('finish-inspection').click()
await mobile.getByText('通常点検24件が未完了です', { exact: true }).waitFor()
await mobile.getByTestId('complete-standard').click()
await mobile.getByText('必要な入力が揃いました', { exact: true }).waitFor()
await mobile.getByTestId('confirm-complete').click()
await mobile.getByTestId('complete-screen').waitFor()
await mobile.getByText('管理側へ提出済み', { exact: true }).waitFor()
await mobile.screenshot({ path: 'artifacts/05-mobile-complete.png', fullPage: true })

// 管理画面をリロードして既存依頼を再取得しても、保存済み写真URLが復元されることを確認
await page.reload({ waitUntil: 'networkidle' })
await page.getByTestId('nav-inspection').click()
await page.getByTestId('open-inspection').click()
await page.getByTestId('request-field').click()
await page.getByTestId('assignment-modal').waitFor()
await page.locator('.admin-photo-grid img').first().waitFor()
await page.getByRole('button', { name: /最新状態に更新/ }).click()
await page.getByText('提出済み', { exact: true }).waitFor()
await page.getByText('DCコネクタに変色あり', { exact: true }).waitFor()
await page.getByText('5枚', { exact: true }).waitFor()
await page.screenshot({ path: 'artifacts/06-admin-result.png', fullPage: true })
await page.getByTestId('make-report-from-field').click()

await page.getByTestId('photo-review-screen').waitFor()
await page.getByRole('heading', { name: '現場写真の確認・差し替え' }).waitFor()
const reviewCards = page.getByTestId('review-photo-card')
await reviewCards.nth(0).getByText('PCS正面', { exact: true }).waitFor()
await page.getByTestId('replace-photo').first().setInputFiles(photo)
await page.getByTestId('confirm-photo-layout').waitFor({ state: 'visible' })
await page.screenshot({ path: 'artifacts/07-photo-review.png', fullPage: true })
await page.getByTestId('confirm-photo-layout').click()

await page.getByTestId('report-screen').waitFor()
console.log('Report screen opened')
await page.getByTestId('report-photo-source').first().dragTo(page.getByTestId('report-drop-findings'))
await page.getByTestId('report-drop-findings').getByTestId('report-image-block').waitFor()
await page.getByText(/通常点検24項目および重点点検4項目/).waitFor()
await page.getByRole('button', { name: 'PDFプレビュー' }).click()
await page.getByRole('dialog').waitFor()
await page.getByTestId('pdf-photos-findings').locator('img').first().waitFor()
await page.screenshot({ path: 'artifacts/09-pdf-preview.png', fullPage: true })
await page.getByRole('button', { name: '閉じる' }).click()
await page.getByTestId('register-misora').click()
await page.getByText('MISORA登録済み（モック）', { exact: true }).waitFor()
await page.locator('.report-image-block img').first().waitFor()
await page.screenshot({ path: 'artifacts/08-report.png', fullPage: true })

await page.getByRole('button', { name: '写真確認へ戻る' }).click()
await page.getByTestId('photo-review-screen').waitFor()
await page.getByRole('button', { name: '現場結果へ戻る' }).click()
await page.getByTestId('assignment-modal').waitFor()
page.once('dialog', dialog => dialog.accept())
await page.getByTestId('reset-inspection').click()
await page.getByText('依頼済み', { exact: true }).waitFor()
await mobile.reload({ waitUntil: 'networkidle' })
await mobile.getByTestId('mobile-start').waitFor()
await mobile.getByText('入力・写真は管理側へ自動同期されます。', { exact: true }).waitFor()

await page.getByRole('button', { name: '閉じる' }).click()
await page.getByTestId('nav-monitoring').click()
await page.getByTestId('monitoring-incident-row').click()
await page.getByTestId('incident-inspection-request').click()
await page.getByTestId('assignment-modal').waitFor()
await page.getByText('青森大間発電所', { exact: false }).last().waitFor()

if (errors.length) throw new Error(`Browser console errors:\n${errors.join('\n')}`)
console.log('Flow check passed: monitoring request → smartphone upload → report layout/PDF → reset')
await browser.close()
